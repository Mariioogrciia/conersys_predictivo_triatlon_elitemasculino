def to_alpha(text):
    text = str(text).upper().strip()
    replacements = {
        'Á': 'A', 'É': 'E', 'Í': 'I', 'Ó': 'O', 'Ú': 'U', 'Ü': 'U', 'Ñ': 'N',
        'Ò': 'O', 'Ó': 'O',
    }
    for orig, rep in replacements.items():
        text = text.replace(orig, rep)
    # Remove any other non-alphanumeric bytes (including replacement chars)
    return re.sub(r'[^A-Z0-9]', '', text)

def run_refinement():
    print("Iniciando inyección final de los 92+31+57 clubes desconocidos con mapeo robusto...")
    
    if not os.path.exists(CACHE_PATH):
        print(f"Error: No se encontró la caché en {CACHE_PATH}")
        return
        
    with open(CACHE_PATH, 'r', encoding='utf-8') as f:
        cache = json.load(f)
        
    print(f"Caché actual contiene {len(cache)} clubes.")
    
    # Precalculamos las claves alfanuméricas de nuestra base de datos final
    alpha_db = {}
    for key, val in UNMAPPED_CLUBS.items():
        alpha_db[to_alpha(key)] = val
        
    injected = 0
    updated_keys = []
    
    # Primero: actualizar entradas existentes en la caché que son DESCONOCIDA
    for club in list(cache.keys()):
        c_alpha = to_alpha(club)
        if c_alpha in alpha_db:
            ciudad, prov, lat, lng = alpha_db[c_alpha]
            cache[club] = {
                'lat': lat,
                'lng': lng,
                'ciudad': ciudad,
                'provincia': prov
            }
            injected += 1
            updated_keys.append(club)
            
    # Segundo: Asegurarnos de que todas las variantes literales de UNMAPPED_CLUBS estén en la caché
    for key, (ciudad, prov, lat, lng) in UNMAPPED_CLUBS.items():
        key_upper = key.upper().strip()
        if key_upper not in cache:
            cache[key_upper] = {
                'lat': lat,
                'lng': lng,
                'ciudad': ciudad,
                'provincia': prov
            }
            injected += 1
            updated_keys.append(key_upper)
            
    with open(CACHE_PATH, 'w', encoding='utf-8') as f:
        json.dump(cache, f, ensure_ascii=False, indent=2)
        
    print(f"Completado. Se inyectaron/actualizaron {injected} registros en {CACHE_PATH}.")

